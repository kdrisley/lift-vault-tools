/* Lift Vault Tools — Strength Standards ("How strong am I?")
 * ------------------------------------------------------------------------
 * Enter sex, lift, and bodyweight (optionally what you lifted) to see the
 * strength tiers for your weight class and where you'd rank. Numbers are
 * real competition percentiles from the OpenPowerlifting dataset (raw
 * lifters, IPF weight classes): intermediate is the median competitor,
 * advanced the top 20%, elite the top 5%, world class the top 1%.
 *
 * Data precomputed by data/build-standards.py from the powerliftingrecords.com
 * database (snapshot 2026-04-04). For the live version filterable by
 * federation, equipment, and age, the tool links to Powerlifting Records.
 *
 * compute() is pure and dual-exported for the Node golden-vector tests.
 * ------------------------------------------------------------------------ */
(function () {
	'use strict';

	var LB_PER_KG = 2.2046226;

	// Auto-generated by data/build-standards.py. Raw lifters, IPF classes, kg.
	// Tiers per class: [intermediate, advanced, elite, worldclass] = top 50/20/5/1%.
	var STANDARDS = {
		m: {
			squat: { '59': [112.5, 150, 180, 205], '66': [150, 177.5, 205, 230], '74': [167.5, 195, 225, 250], '83': [185, 215, 245, 270], '93': [200, 230, 260, 287.5], '105': [210, 245, 280, 310], '120': [225, 262.5, 300, 330], '120plus': [240, 285, 330, 375] },
			bench: { '59': [75, 102.5, 130, 165], '66': [97.5, 120, 140, 162.5], '74': [110, 132.5, 152.5, 175], '83': [125, 145, 170, 190], '93': [135, 160, 182.5, 207.5], '105': [147.5, 172.5, 200, 220], '120': [160, 190, 215, 240], '120plus': [172.5, 205, 235, 265] },
			deadlift: { '59': [140, 180, 210, 237.5], '66': [180, 210, 240, 265], '74': [200, 227.5, 257.5, 285], '83': [215, 245, 275, 302.5], '93': [227.5, 260, 290, 320], '105': [240, 272.5, 305, 335], '120': [250, 285, 320, 350], '120plus': [257.5, 297.5, 335, 367.5] },
			total: { '59': [330, 427.5, 505, 560], '66': [427.5, 500, 570, 635], '74': [477.5, 550, 620, 682.5], '83': [522.5, 597.5, 670, 735], '93': [557.5, 637.5, 715, 780], '105': [592.5, 677.5, 760, 825], '120': [625, 715, 805, 877.5], '120plus': [657.5, 765, 867.5, 952.5] }
		},
		f: {
			squat: { '47': [75, 97.5, 117.5, 135], '52': [90, 110, 132.5, 150], '57': [100, 120, 140, 160], '63': [105, 127.5, 150, 167.5], '69': [112.5, 135, 160, 180], '76': [117.5, 142.5, 167.5, 190], '84': [120, 147.5, 175, 197.5], '84plus': [127.5, 160, 190, 225] },
			bench: { '47': [45, 57.5, 75, 95], '52': [52.5, 65, 80, 95], '57': [55, 70, 85, 100], '63': [60, 72.5, 90, 107.5], '69': [62.5, 77.5, 95, 115], '76': [65, 82.5, 100, 120], '84': [67.5, 85, 105, 125], '84plus': [70, 87.5, 110, 137.5] },
			deadlift: { '47': [97.5, 120, 142.5, 162.5], '52': [112.5, 135, 157.5, 175], '57': [122.5, 145, 165, 185], '63': [127.5, 150, 172.5, 195], '69': [135, 157.5, 182.5, 205], '76': [140, 165, 190, 212.5], '84': [142.5, 170, 195, 220], '84plus': [147.5, 175, 200, 230] },
			total: { '47': [217.5, 275, 327.5, 370], '52': [257.5, 307.5, 360, 405], '57': [280, 330, 385, 430], '63': [292.5, 347.5, 402.5, 455], '69': [310, 365, 425, 485], '76': [325, 382.5, 447.5, 507.5], '84': [332.5, 395, 457.5, 520], '84plus': [347.5, 415, 490, 565] }
		}
	};
	var BOUNDS = { m: [59, 66, 74, 83, 93, 105, 120], f: [47, 52, 57, 63, 69, 76, 84] };
	var TIER_LABELS = ['Intermediate', 'Advanced', 'Elite', 'World class'];
	var TIER_PCT = ['top 50%', 'top 20%', 'top 5%', 'top 1%'];

	function classKeyFor(sex, bwKg) {
		var b = BOUNDS[sex];
		for (var i = 0; i < b.length; i++) { if (bwKg <= b[i]) return String(b[i]); }
		return b[b.length - 1] + 'plus';
	}
	function classLabelFor(key, sex) {
		if (key.indexOf('plus') >= 0) return key.replace('plus', '') + '+ kg';
		return '-' + key + ' kg';
	}

	// PURE.
	function computeStandards(v) {
		var unit = v.unit === 'lb' ? 'lb' : 'kg';
		var sex = v.sex === 'f' ? 'f' : 'm';
		var lift = Object.prototype.hasOwnProperty.call(STANDARDS[sex], v.lift) ? v.lift : 'squat';
		var toKg = unit === 'lb' ? 1 / LB_PER_KG : 1;
		var bwKg = (parseFloat(v.bodyweight) || 0) * toKg;
		var liftedKg = (parseFloat(v.lifted) || 0) * toKg;

		var out = { unit: unit, sex: sex, lift: lift, valid: bwKg > 0 };
		if (!out.valid) return out;

		var key = classKeyFor(sex, bwKg);
		out.classKey = key;
		out.classLabel = classLabelFor(key, sex);
		out.thresholds = STANDARDS[sex][lift][key]; // kg

		if (liftedKg > 0) {
			out.lifted = liftedKg;
			var t = out.thresholds, idx = -1;
			for (var i = t.length - 1; i >= 0; i--) { if (liftedKg >= t[i]) { idx = i; break; } }
			out.tier = idx === -1 ? 'Novice' : TIER_LABELS[idx];
			out.tierPct = idx === -1 ? 'below the top 50%' : TIER_PCT[idx];
			out.tierIdx = idx;
		} else {
			out.tier = '';
			out.tierIdx = -2;
		}
		return out;
	}

	/* ---------- rendering (browser only) ---------- */
	function disp(kg, unit) { return unit === 'lb' ? Math.round(kg * LB_PER_KG / 5) * 5 : kg; }
	function fmt(n) { return (Math.round(n * 100) / 100).toString(); }

	function render(res, host) {
		host.innerHTML = '';
		if (!res.valid) {
			var m0 = document.createElement('div');
			m0.className = 'lvt-note';
			m0.textContent = 'Enter your bodyweight to see the strength standards for your class.';
			host.appendChild(m0);
			return;
		}
		var unit = res.unit;
		var liftName = res.lift.charAt(0).toUpperCase() + res.lift.slice(1);

		if (res.tier) {
			var stat = document.createElement('div');
			stat.className = 'lvt-stat';
			var color = res.tier === 'Novice' ? 'var(--lvt-ink-mid)' : 'var(--lvt-heat)';
			stat.innerHTML =
				'<div class="lvt-stat-label">' + liftName + ' · ' + res.classLabel + '</div>' +
				'<div class="lvt-stat-num" style="color:' + color + '">' + res.tier + '</div>' +
				'<div class="lvt-stat-basis">' + fmt(disp(res.lifted, unit)) + ' ' + unit +
				(res.tierPct.indexOf('below') === 0 ? ', ' + res.tierPct : ', ' + res.tierPct + ' of competitors') + '</div>';
			host.appendChild(stat);
		}

		var rows = res.thresholds.map(function (kg, i) {
			var hl = res.tierIdx === i ? ' class="hl"' : '';
			return '<tr' + hl + '><td>' + TIER_LABELS[i] + '</td><td class="dim">' + TIER_PCT[i] +
				'</td><td>' + fmt(disp(kg, unit)) + ' ' + unit + '</td></tr>';
		}).join('');
		var wrap = document.createElement('div');
		wrap.insertAdjacentHTML('beforeend',
			'<table class="lvt-table"><thead><tr><th>Tier</th><th>Standing</th><th>' + liftName + '</th></tr></thead><tbody>' +
			rows + '</tbody></table>');
		host.appendChild(wrap);

		var note = document.createElement('div');
		note.className = 'lvt-note';
		note.innerHTML = 'Real competition standards for raw lifters in the ' + res.classLabel +
			' class (OpenPowerlifting data). Intermediate is the median competitor, world class the top 1%. ' +
			'For the live version filterable by federation, equipment, and age, see the ' +
			'<a href="https://powerliftingrecords.com/tools/strength-standards/" target="_blank" rel="noopener">strength standards tool on Powerlifting Records</a>.';
		host.appendChild(note);
	}

	var def = {
		id: 'strength-standards',
		version: '0.1.1',
		title: 'Strength Standards Calculator',
		units: ['kg', 'lb'],
		convertOnUnitChange: true,
		inputs: [
			{ id: 'sex', label: 'Sex', type: 'select', convert: false, def: 'm', opts: [
				{ value: 'm', label: 'Men' }, { value: 'f', label: 'Women' }
			] },
			{ id: 'lift', label: 'Lift', type: 'select', convert: false, def: 'squat', opts: [
				{ value: 'squat', label: 'Squat' }, { value: 'bench', label: 'Bench' },
				{ value: 'deadlift', label: 'Deadlift' }, { value: 'total', label: 'Total' }
			] },
			{ id: 'bodyweight', label: 'Bodyweight', type: 'number', min: 20, max: { kg: 300, lb: 660 }, step: 0.5, def: { kg: 90, lb: 200 } },
			{ id: 'lifted', label: 'What you lifted (optional)', type: 'number', min: 0, max: { kg: 1500, lb: 3300 }, step: 2.5, def: { kg: 0, lb: 0 } }
		],
		compute: computeStandards,
		render: render
	};

	if (typeof module !== 'undefined' && module.exports) { module.exports = def; }
	if (typeof window !== 'undefined' && window.LVTools) { window.LVTools.register(def); }
})();
